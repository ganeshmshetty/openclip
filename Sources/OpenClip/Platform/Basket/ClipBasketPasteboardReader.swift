// ClipBasketPasteboardReader.swift
// OpenClip
//
// Reads a single supported item from the general pasteboard for the Clip Basket's scoped ⌘C
// capture. File URLs win over images, images over text; protected and oversized items are skipped
// before any expensive decode.
import AppKit
import Core

enum ClipBasketPasteboardIgnoreReason: String, Sendable, Equatable {
    case protected
    case oversizedImage
    case oversizedText
    case empty
    case unsupported
}

enum ClipBasketPasteboardReadResult: Sendable, Equatable {
    case content(ClipBasketContent)
    case ignored(ClipBasketPasteboardIgnoreReason)
}

struct ClipBasketPasteboardReader: Sendable {
    static let protectedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    static let defaultMaxImageBytes = 25 * 1024 * 1024
    static let defaultMaxTextBytes = Constants.maxTextLength

    let maxImageBytes: Int
    let maxTextBytes: Int

    init(
        maxImageBytes: Int = ClipBasketPasteboardReader.defaultMaxImageBytes,
        maxTextBytes: Int = ClipBasketPasteboardReader.defaultMaxTextBytes
    ) {
        self.maxImageBytes = maxImageBytes
        self.maxTextBytes = maxTextBytes
    }

    func read(from pasteboard: NSPasteboard) -> ClipBasketPasteboardReadResult {
        let typeNames = Set((pasteboard.types ?? []).map(\.rawValue))
        if !Self.protectedTypes.isDisjoint(with: typeNames) {
            return .ignored(.protected)
        }

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            return .content(.files(urls))
        }

        let png = pasteboard.data(forType: .png)
        let tiff = png == nil ? pasteboard.data(forType: .tiff) : nil
        if let data = png ?? tiff, !data.isEmpty {
            guard data.count <= maxImageBytes else {
                return .ignored(.oversizedImage)
            }
            let rep = NSBitmapImageRep(data: data)
            return .content(.image(
                data: data,
                uti: png != nil ? "public.png" : "public.tiff",
                pixelWidth: rep?.pixelsWide,
                pixelHeight: rep?.pixelsHigh
            ))
        }

        let plainData = pasteboard.data(forType: .string)
        let htmlData = pasteboard.data(forType: .html)
        let rtfData = pasteboard.data(forType: .rtf)
        for data in [plainData, htmlData, rtfData].compactMap({ $0 }) where data.count > maxTextBytes {
            return .ignored(.oversizedText)
        }

        let plain = plainData.flatMap { String(data: $0, encoding: .utf8) } ?? pasteboard.string(forType: .string)
        let html = htmlData.flatMap { String(data: $0, encoding: .utf8) } ?? pasteboard.string(forType: .html)
        let rtf = rtfData.flatMap { String(data: $0, encoding: .utf8) } ?? pasteboard.string(forType: .rtf)
        if [plain, html, rtf].compactMap({ $0 }).contains(where: { $0.utf8.count > maxTextBytes }) {
            return .ignored(.oversizedText)
        }
        guard plain != nil || html != nil || rtf != nil else {
            return .ignored(.empty)
        }
        return .content(.text(RichPasteboardPayload(plainText: plain, rtf: rtf, html: html)))
    }
}
